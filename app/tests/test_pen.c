#include <assert.h>
#include <math.h>
#include "pen.h"

int main(void) {
    struct sc_pen pen = {0};
    struct sc_pen_sample sample;
    SDL_Event e = {0};
    e.type = SDL_EVENT_PEN_AXIS;
    e.paxis.which = 7;
    e.paxis.axis = SDL_PEN_AXIS_PRESSURE;
    e.paxis.value = .25f;
    assert(!sc_pen_process(&pen, &e, &sample));
    e.type = SDL_EVENT_PEN_DOWN;
    e.ptouch.which = 7;
    e.ptouch.x = 20;
    e.ptouch.y = 30;
    assert(sc_pen_process(&pen, &e, &sample));
    assert(sample.action == 0 && sample.pressure == .25f);
    e.ptouch.which = 8;
    assert(!sc_pen_process(&pen, &e, &sample));
    e.type = SDL_EVENT_PEN_MOTION;
    e.pmotion.which = 7;
    e.pmotion.x = 40;
    e.pmotion.y = 50;
    assert(sc_pen_process(&pen, &e, &sample));
    assert(sample.action == 2 && sample.x == 40 && sample.y == 50);
    e.type = SDL_EVENT_PEN_AXIS;
    e.paxis.which = 7;
    e.paxis.axis = SDL_PEN_AXIS_PRESSURE;
    e.paxis.value = .75f;
    assert(sc_pen_process(&pen, &e, &sample));
    assert(sample.pressure == .75f && sample.x == 40);
    e.paxis.value = NAN;
    assert(sc_pen_process(&pen, &e, &sample));
    assert(sample.action == 1 && !pen.down);
    e.type = SDL_EVENT_PEN_UP;
    e.ptouch.which = 7;
    assert(!sc_pen_process(&pen, &e, &sample));
    e.type = SDL_EVENT_PEN_DOWN;
    e.ptouch.pen_state = SDL_PEN_INPUT_ERASER_TIP;
    assert(!sc_pen_process(&pen, &e, &sample));
    e.ptouch.pen_state = 0;
    assert(sc_pen_process(&pen, &e, &sample));
    e.type = SDL_EVENT_WINDOW_FOCUS_LOST;
    assert(sc_pen_process(&pen, &e, &sample));
    assert(sample.action == 1 && !pen.down);
    e.type = SDL_EVENT_PEN_DOWN;
    assert(sc_pen_process(&pen, &e, &sample));
    e.type = SDL_EVENT_PEN_PROXIMITY_OUT;
    e.pproximity.which = 7;
    assert(sc_pen_process(&pen, &e, &sample));
    assert(sample.action == 1);
    e.type = SDL_EVENT_PEN_DOWN;
    e.ptouch.which = 7;
    e.ptouch.pen_state = 0;
    assert(sc_pen_process(&pen, &e, &sample));
    e.type = SDL_EVENT_PEN_AXIS;
    e.paxis.which = 7;
    e.paxis.axis = SDL_PEN_AXIS_PRESSURE;
    e.paxis.value = .8f;
    assert(sc_pen_process(&pen, &e, &sample));
    e.type = SDL_EVENT_PEN_UP;
    e.ptouch.which = 7;
    assert(sc_pen_process(&pen, &e, &sample));
    e.type = SDL_EVENT_PEN_DOWN;
    e.ptouch.which = 7;
    assert(sc_pen_process(&pen, &e, &sample));
    assert(sample.pressure == 0); // Never reuse the preceding stroke's pressure.
    e.type = SDL_EVENT_MOUSE_MOTION;
    e.motion.which = SDL_PEN_MOUSEID;
    assert(sc_pen_is_synthetic(&e));
    e.motion.which = 123;
    assert(!sc_pen_is_synthetic(&e));
    e.type = SDL_EVENT_FINGER_DOWN;
    e.tfinger.touchID = SDL_PEN_TOUCHID;
    assert(sc_pen_is_synthetic(&e));
    e.tfinger.touchID = 123;
    assert(!sc_pen_is_synthetic(&e));
    return 0;
}
